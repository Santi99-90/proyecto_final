    private void liberar(){
        if (clienteActual != null) {
            try {
                clienteDAO.cambiarEstado(clienteActual.getId(), 0);
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error al liberar el cliente: " + e.getMessage());
            }
        }
        if (cajeroActual != null) {
            try {
                cajeroDAO.cambiarEstado(cajeroActual.getId(), 0);
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error al liberar el cajero: " + e.getMessage());
            }
        }
        clienteActual = null;
        cajeroActual = null;
        lblCliente.setText("---");
        txtNumCajero.setEditable(true);
        txtNumCuenta.setEditable(true);
    }
    
    private void mostrarBilletesEntregados(int [] distribucion){
        DefaultTableModel modelo = (DefaultTableModel) tabla_billetes.getModel();
        modelo.setRowCount(0);
        for (int i = 0; i < distribucion.length; i++) {
            if (distribucion[i] > 0) {
                int denominacion = Dispensador.denominaciones[i];
                modelo.addRow(new Object[]{denominacion, distribucion[i], denominacion*distribucion[i]});
            }
        }
    }

